// This build serves no billing activation or authorization routes, so every payment step stops here.
export const PAYMENTS_UNAVAILABLE = "Payments aren't available in this version."

const PAYMENT_ORGANIZATION_ERROR = 'This payment link is missing its organization. Return to billing and start again.'

interface PaymentFlow {
    organizationId: string
    organizationName: string | null
}

type CompletionParams = Record<string, string | boolean>

const navigateAfterPayment = (redirectPath: string | null, searchParams: CompletionParams): void => {
    const onCallbackPage = router.values.location.pathname === urls.billingAuthorizationStatus()
    if (!redirectPath && !onCallbackPage) {
        router.actions.push(router.values.location.pathname, { ...router.values.searchParams, ...searchParams })
        return
    }
    const url = new URL(redirectPath || urls.organizationBilling(), window.location.origin)
    router.actions.push(url.pathname, { ...Object.fromEntries(url.searchParams.entries()), ...searchParams })
}

export const paymentEntryLogic = kea<paymentEntryLogicType>([
    path(['scenes', 'billing', 'PaymentEntryLogic']),
    connect({
        logic: [billingLogic],
    }),
    actions({
        setClientSecret: (clientSecret: string | null) => ({ clientSecret }),
        setLoading: (loading: boolean) => ({ loading }),
        setStripeError: (error: string | null) => ({ error }),
        setApiError: (error: string | null) => ({ error }),
        clearErrors: true,
        beginPaymentFlow: (organizationId: string, redirectPath: string | null = null) => {
            const selected = organizationLogic.values.currentOrganization
            const flow: PaymentFlow = {
                organizationId,
                organizationName: selected?.id === organizationId ? selected.name : null,
            }
            return { flow, redirectPath }
        },
        cancelPaymentFlow: true,
        settlePaymentFlow: true,
        completePaymentFlow: (redirectPath: string | null, searchParams: CompletionParams) => ({
            redirectPath,
            searchParams,
        }),
        setCompletedPaymentOrganization: (organization: { id: string; name: string }) => ({ organization }),
        viewCompletedPaymentOrganization: true,
        initiateAuthorization: true,
        confirmPayment: (stripe: Stripe, elements: StripeElements) => ({ stripe, elements }),
        pollAuthorizationStatus: (paymentIntentId?: string) => ({ paymentIntentId }),
        setAuthorizationStatus: (status: string | null) => ({ status }),
        startPaymentEntryFlow: (product?: BillingProductV2Type | null, redirectPath?: string | null) => ({
            product,
            redirectPath,
        }),
        upgradeProducts: (products: string, redirectPath: string | null) => ({ products, redirectPath }),
        showPaymentEntryModal: true,
        hidePaymentEntryModal: true,
        setRedirectPath: (redirectPath: string | null) => ({ redirectPath }),
    }),
    reducers({
        paymentFlow: [
            null as PaymentFlow | null,
            { beginPaymentFlow: (_, { flow }) => flow, cancelPaymentFlow: () => null },
        ],
        paymentSubmitted: [
            false,
            {
                confirmPayment: () => true,
                setStripeError: () => false,
                beginPaymentFlow: () => false,
                settlePaymentFlow: () => false,
            },
        ],
        completedPaymentOrganization: [
            null as { id: string; name: string } | null,
            {
                setCompletedPaymentOrganization: (_, { organization }) => organization,
                beginPaymentFlow: () => null,
                hidePaymentEntryModal: () => null,
            },
        ],
        clientSecret: [
            null as string | null,
            {
                setClientSecret: (_, { clientSecret }) => clientSecret,
                beginPaymentFlow: () => null,
                hidePaymentEntryModal: () => null,
                settlePaymentFlow: () => null,
            },
        ],
        isLoading: [
            false,
            {
                setLoading: (_, { loading }) => loading,
                beginPaymentFlow: () => false,
                hidePaymentEntryModal: () => false,
                settlePaymentFlow: () => false,
            },
        ],
        stripeError: [
            null as string | null,
            { setStripeError: (_, { error }) => error, clearErrors: () => null, beginPaymentFlow: () => null },
        ],
        apiError: [
            null as string | null,
            { setApiError: (_, { error }) => error, clearErrors: () => null, beginPaymentFlow: () => null },
        ],
        authorizationStatus: [
            null as string | null,
            { setAuthorizationStatus: (_, { status }) => status, beginPaymentFlow: () => null },
        ],
        paymentEntryModalOpen: [false, { showPaymentEntryModal: () => true, hidePaymentEntryModal: () => false }],
        redirectPath: [
            null as string | null,
            {
                setRedirectPath: (_, { redirectPath }) => redirectPath,
                beginPaymentFlow: (_, { redirectPath }) => redirectPath,
                settlePaymentFlow: () => null,
            },
        ],
    }),
    selectors({
        paymentOrganizationId: [
            (s) => [s.paymentFlow],
            (flow: PaymentFlow | null): string | null => flow?.organizationId ?? null,
        ],
        stripeReturnUrl: [
            (s) => [s.paymentOrganizationId, s.redirectPath],
            (organizationId: string | null, redirectPath: string | null): string | null => {
                if (!organizationId) {
                    return null
                }
                const url = new URL(urls.billingAuthorizationStatus(), window.location.origin)
                url.searchParams.set('organization_id', organizationId)
                if (redirectPath) {
                    url.searchParams.set('postRedirectPath', redirectPath)
                }
                return url.toString()
            },
        ],
    }),
    listeners(({ actions, values, cache }) => {
        // Handlers run only while the flow that started the step is still the live one.
        const runPaymentStep = async <T>(
            request: () => Promise<T>,
            onSuccess: (result: T) => void | Promise<void>,
            onError?: (error: unknown) => void
        ): Promise<void> => {
            const flow = values.paymentFlow
            const isCurrent = (): boolean => !!flow && !cache.disposables.isDisposed && values.paymentFlow === flow
            let result: T
            try {
                result = await request()
            } catch (error) {
                if (isCurrent()) {
                    onError?.(error)
                }
                return
            }
            if (isCurrent()) {
                await onSuccess(result)
            }
        }

        const activationUnavailable = (): void => {
            actions.setLoading(false)
            lemonToast.error(PAYMENTS_UNAVAILABLE)
        }

        // Replacing a submitted flow would drop its result, so a new flow waits until it settles.
        const startFlow = (redirectPath: string | null): string | null => {
            if (values.paymentSubmitted) {
                lemonToast.info("We're still confirming your last payment.")
                return null
            }
            const organizationId = organizationLogic.values.currentOrganization?.id
            if (!organizationId) {
                lemonToast.error('Reload the page before updating payment details.')
                return null
            }
            actions.beginPaymentFlow(organizationId, redirectPath)
            return organizationId
        }

        return {
            beginPaymentFlow: () => {
                cache.disposables.dispose('authorizationPoll')
            },
            completePaymentFlow: async ({ redirectPath, searchParams }) => {
                const flow = values.paymentFlow
                if (!flow || cache.completedPaymentFlow === flow) {
                    return
                }
                cache.completedPaymentFlow = flow
                const { organizationId } = flow
                await runPaymentStep(
                    // Generated organization teams/features are readonly arrays; the stores use OrganizationType.
                    () =>
                        retrieveOrganization(organizationId)
                            .then((organization) => organization as unknown as OrganizationType)
                            .catch(() => null),
                    (fetchedOrganization) => {
                        actions.settlePaymentFlow()
                        const organization = fetchedOrganization?.id === organizationId ? fetchedOrganization : null
                        if (organizationLogic.values.currentOrganization?.id !== organizationId) {
                            actions.setCompletedPaymentOrganization({
                                id: organizationId,
                                name: flow.organizationName || organization?.name || 'the original organization',
                            })
                            actions.clearErrors()
                            if (router.values.location.pathname !== urls.billingAuthorizationStatus()) {
                                actions.showPaymentEntryModal()
                            }
                            return
                        }
                        if (organization) {
                            organizationLogic.actions.loadCurrentOrganizationSuccess(organization)
                            const user = userLogic.values.user
                            if (user) {
                                userLogic.actions.loadUserSuccess({ ...user, organization })
                            }
                        }
                        navigateAfterPayment(redirectPath, searchParams)
                        actions.hidePaymentEntryModal()
                    }
                )
            },
            viewCompletedPaymentOrganization: async () => {
                const organization = values.completedPaymentOrganization
                if (!organization) {
                    return
                }
                // Not userLogic.updateCurrentOrganization: it skips the switch while the cached user names this
                // organization, and that cache can lag a switch made in another tab.
                try {
                    await usersPartialUpdate('@me', { set_current_organization: organization.id })
                } catch {
                    lemonToast.error('Could not switch organization. Try again.')
                    return
                }
                sidePanelStateLogic.findMounted()?.actions.closeSidePanel()
                window.location.href = urls.organizationBilling()
            },
            startPaymentEntryFlow: async ({ redirectPath }) => {
                const { billing, selfServeBillingNotice } = billingLogic.values
                if (selfServeBillingNotice) {
                    lemonToast.info(selfServeBillingNotice)
                    return
                }
                const organizationId = startFlow(redirectPath || null)
                if (!organizationId) {
                    return
                }
                if (!billing?.customer_id) {
                    actions.showPaymentEntryModal()
                    return
                }
                activationUnavailable()
            },
            upgradeProducts: async ({ redirectPath }) => {
                const organizationId = startFlow(redirectPath)
                if (!organizationId) {
                    return
                }
                activationUnavailable()
            },
            initiateAuthorization: async () => {
                if (values.completedPaymentOrganization) {
                    return
                }
                const organizationId = values.paymentOrganizationId
                if (!organizationId) {
                    actions.setApiError(PAYMENT_ORGANIZATION_ERROR)
                    return
                }
                actions.setClientSecret(null)
                actions.clearErrors()
                actions.setApiError(PAYMENTS_UNAVAILABLE)
            },
            confirmPayment: async ({ stripe, elements }) => {
                const returnUrl = values.stripeReturnUrl
                if (!returnUrl) {
                    actions.setStripeError('Return to billing and start the payment flow again.')
                    return
                }
                actions.setLoading(true)
                const failConfirmation = (error: unknown, message: string): void => {
                    actions.setLoading(false)
                    actions.setStripeError(message)
                    posthog.captureException(new Error('payment entry stripe error', { cause: error }))
                }
                await runPaymentStep(
                    () =>
                        stripe.confirmPayment({
                            elements,
                            confirmParams: { return_url: returnUrl },
                            redirect: 'if_required',
                        }),
                    (result) => {
                        if (result.error) {
                            failConfirmation(result.error, result.error.message || 'Payment failed. Please try again.')
                        } else {
                            actions.pollAuthorizationStatus(result.paymentIntent.id)
                        }
                    },
                    (error) => failConfirmation(error, 'Payment failed. Please try again.')
                )
            },
            pollAuthorizationStatus: async () => {
                const organizationId = values.paymentOrganizationId
                if (!organizationId) {
                    actions.setApiError(PAYMENT_ORGANIZATION_ERROR)
                    return
                }
                actions.setApiError(PAYMENTS_UNAVAILABLE)
                actions.settlePaymentFlow()
            },
            hidePaymentEntryModal: () => {
                if (!values.paymentSubmitted) {
                    actions.cancelPaymentFlow()
                }
                actions.clearErrors()
            },
        }
    }),
    afterMount(({ actions }) => {
        const params = new URLSearchParams(window.location.search)
        const organizationId = params.get('organization_id')
        if (organizationId && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(organizationId)) {
            actions.beginPaymentFlow(organizationId, params.get('postRedirectPath'))
        }
    }),
])
